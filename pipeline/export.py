# pipeline/export.py
# Stage: EXPORT the finished dataset as JSON and SQL, and write a manifest with checksums.
# Reads : output/data, output/ground_truth, output/reports (CSV files)
# Writes: output/json/*.json, output/json/ground_truth/*.json,
#         output/sql/schema.sql, output/sql/seed.sql, output/manifest.json

import sys
from pathlib import Path
sys.path.append(str(Path(__file__).resolve().parent.parent))

import argparse
import json
import platform

import numpy as np
import pandas as pd

from config import SEED, DATA_DIR, GT_DIR, REPORT_DIR, JSON_DIR, SQL_DIR, OUTPUT
from utils import file_checksum

# (table, primary key columns, [(column, parent table, parent column)])  parents come first
TABLES = [
    ("warehouse", ["warehouse_id"], []),
    ("zone", ["zone_id"], [("warehouse_id", "warehouse", "warehouse_id")]),
    ("sensor", ["sensor_id"], []),
    ("sensor_zone_map", ["map_id"], [("sensor_id", "sensor", "sensor_id"), ("zone_id", "zone", "zone_id")]),
    ("storage_requirement", ["requirement_id"], []),
    ("inventory_lot", ["lot_id"], [("requirement_id", "storage_requirement", "requirement_id")]),
    ("lot_zone_assignment", ["assignment_id"], [("lot_id", "inventory_lot", "lot_id"), ("zone_id", "zone", "zone_id")]),
    ("sensor_reading", ["reading_id"], [("sensor_id", "sensor", "sensor_id")]),
    ("door_event", ["door_event_id"], [("zone_id", "zone", "zone_id")]),
    ("sensor_gap", ["gap_id"], [("sensor_id", "sensor", "sensor_id")]),
    ("alarm", ["alarm_id"], [("zone_id", "zone", "zone_id"), ("sensor_id", "sensor", "sensor_id")]),
    ("alarm_status_history", ["history_id"], [("alarm_id", "alarm", "alarm_id")]),
    ("alarm_affected_lot", ["alarm_id", "lot_id"], [("alarm_id", "alarm", "alarm_id"), ("lot_id", "inventory_lot", "lot_id")]),
    ("inspection", ["inspection_id"], [("alarm_id", "alarm", "alarm_id"), ("lot_id", "inventory_lot", "lot_id")]),
    ("remediation", ["remediation_id"], [("inspection_id", "inspection", "inspection_id"), ("lot_id", "inventory_lot", "lot_id")]),
]
BATCH = 5000


def sql_type(s):
    if pd.api.types.is_bool_dtype(s) or pd.api.types.is_integer_dtype(s):
        return "INTEGER"
    if pd.api.types.is_float_dtype(s):
        return "TEXT" if s.isna().all() else "REAL"
    return "TEXT"


def sql_values(df):
    """Turn every column into SQL text, then join the columns row by row."""
    cols = []
    for c in df.columns:
        s = df[c]
        if pd.api.types.is_bool_dtype(s):
            out = s.astype(int).astype(str)
        elif pd.api.types.is_numeric_dtype(s) and not s.isna().all():
            out = s.astype(object).where(s.notna(), None).map(lambda v: "NULL" if v is None else repr(v.item() if hasattr(v, "item") else v))
        else:
            out = s.astype(object).where(s.notna(), None).map(
                lambda v: "NULL" if v is None else "'" + str(v).replace("'", "''") + "'")
        cols.append(out.astype(str))
    row = cols[0]
    for c in cols[1:]:
        row = row + "," + c
    return "(" + row + ")"


def write_schema(frames):
    lines = ["-- Warehouse monitoring schema (SQLite / ANSI style). Generated by pipeline/export.py", ""]
    for name, pk, fks in TABLES:
        df = frames[name]
        defs = [f"    {c} {sql_type(df[c])}" + (" NOT NULL" if c in pk else "") for c in df.columns]
        defs.append(f"    PRIMARY KEY ({', '.join(pk)})")
        for col, pt, pc in fks:
            defs.append(f"    FOREIGN KEY ({col}) REFERENCES {pt}({pc})")
        lines += [f"CREATE TABLE {name} (", ",\n".join(defs), ");", ""]
    (SQL_DIR / "schema.sql").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_seed(frames):
    with open(SQL_DIR / "seed.sql", "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Seed data. Load schema.sql first. Generated by pipeline/export.py\n")
        f.write("BEGIN TRANSACTION;\n")
        for name, _, _ in TABLES:
            df = frames[name]
            head = f"INSERT INTO {name} ({', '.join(df.columns)}) VALUES\n"
            for i in range(0, len(df), BATCH):
                f.write(head + ",\n".join(sql_values(df.iloc[i:i + BATCH])) + ";\n")
        f.write("COMMIT;\n")


def write_json(frames):
    JSON_DIR.mkdir(parents=True, exist_ok=True)
    for name, df in frames.items():
        df.to_json(JSON_DIR / f"{name}.json", orient="records", indent=1)
    gt_dir = JSON_DIR / "ground_truth"
    gt_dir.mkdir(parents=True, exist_ok=True)
    for p in sorted(GT_DIR.glob("*.csv")):
        pd.read_csv(p).to_json(gt_dir / f"{p.stem}.json", orient="records", indent=1)


def write_manifest(scale):
    files = []
    for folder in (DATA_DIR, GT_DIR, REPORT_DIR, JSON_DIR, SQL_DIR):
        for p in sorted(folder.rglob("*")):
            if p.is_file():
                rows = ""
                if p.suffix == ".csv":
                    with open(p, "rb") as fh:
                        rows = sum(1 for _ in fh) - 1
                files.append({"file": str(p.relative_to(OUTPUT)).replace("\\", "/"), "rows": rows,
                              "bytes": p.stat().st_size, "sha256": file_checksum(p)})
    manifest = {
        "project": "Warehouse monitoring synthetic dataset",
        "seed": SEED, "scale": scale,
        "generator_command": f"python run_all.py --seed {SEED} --scale {scale}",
        "external_data": "none. All data is synthetic. No public data set was downloaded or redistributed.",
        "python": platform.python_version(), "pandas": pd.__version__, "numpy": np.__version__,
        "files": files}
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8", newline="\n")
    return len(files)


def main(scale="full"):
    frames = {name: pd.read_csv(DATA_DIR / f"{name}.csv") for name, _, _ in TABLES}
    SQL_DIR.mkdir(parents=True, exist_ok=True)
    write_schema(frames)
    write_seed(frames)
    write_json(frames)
    n = write_manifest(scale)
    print(f"Exported {len(frames)} tables to JSON and SQL; manifest lists {n} files.")
    print(f"  {SQL_DIR / 'schema.sql'}\n  {SQL_DIR / 'seed.sql'}\n  {JSON_DIR}\n  {OUTPUT / 'manifest.json'}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--scale", default="full", choices=["starter", "full"])
    main(parser.parse_args().scale)